#!/usr/bin/env python3
#
# Write prebuilt/apps/GoogleMessages/Android.bp from Google Messages' APK.
#
# A built-in app that has not been updated gets no native-library extraction
# from Android (PackageAbiHelperImpl.shouldExtractLibs), and the Messages APK
# keeps its libraries compressed with extractNativeLibs left at true. So the
# APK ships unchanged ("preprocessed", keeping Google's signature) and its
# 64-bit libraries are installed to /product/lib64, which Android's linker
# searches for built-in product apps. fetch-prebuilts.sh unpacks them from
# the pinned APK into lib/arm64 (not in git). Run again when the APK changes:
#   gen-messages-libs.py <GoogleMessages.apk> <vendor/zeros>
#
# SPDX-License-Identifier: Apache-2.0
#
import pathlib
import sys
import zipfile

apk, vendor = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
libs = sorted(pathlib.PurePosixPath(n).name for n in zipfile.ZipFile(apk).namelist()
              if n.startswith("lib/arm64-v8a/") and n.endswith(".so"))
mods = ["GoogleMessages_" + l[:-3] for l in libs]

out = ["""//
// Google Messages, the Google build's SMS app (decided 24 October 2026, after a
// day's trial: RCS and reactions). Google's own signed APK, kept with its
// signature so Play Store updates install over it, as with Gboard. The APK is
// Google's to distribute, not ZeroS's, so it is not in git: it is copied to the
// build server and checked against the SHA-256 and signing certificate pinned
// in SOURCE (prebuilt/apps/fetch-prebuilts.sh). Only in the Google build
// (config/gapps.mk), which also makes it the default SMS app.
//
// Not privileged: as a privileged app every privileged permission it asks for
// would have to be in MindTheGapps' allowlist or the phone would not boot; the
// trial ran it as an ordinary app and RCS worked.
//
// Native libraries: the APK keeps them compressed and asks Android to extract
// them, which Android does not do for a built-in app until it is updated. The
// APK ships unchanged and its 64-bit libraries go to /product/lib64, where the
// linker looks for built-in product apps. fetch-prebuilts.sh unpacks them from
// the pinned APK into lib/arm64 (not in git).
//
// Generated by build/tools/gen-messages-libs.py; run it again when the APK
// changes.
//
// SPDX-License-Identifier: Apache-2.0
//

android_app_import {
    name: "GoogleMessages",
    apk: "GoogleMessages.apk",
    presigned: true,
    preprocessed: true,
    dex_preopt: {
        enabled: false,
    },
    product_specific: true,
    // Replaces LineageOS's Messaging, so the phone has exactly one SMS app.
    overrides: ["messaging"],
    required: ["""]
out += ['        "%s",' % m for m in mods]
out += ["    ],", "}", ""]
for l, m in zip(libs, mods):
    out += ["cc_prebuilt_library_shared {",
            '    name: "%s",' % m,
            '    stem: "%s",' % l[:-3],
            '    srcs: ["lib/arm64/%s"],' % l,
            '    compile_multilib: "64",',
            "    product_specific: true,",
            "    check_elf_files: false,",
            "    strip: {",
            "        none: true,",
            "    },",
            "}",
            ""]
(vendor / "prebuilt/apps/GoogleMessages/Android.bp").write_text("\n".join(out))
print(f"{len(libs)} libraries")
